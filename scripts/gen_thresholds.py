"""Plausibility thresholds from the train split, and the plan §5.2 validation figures (#33).

    just gen-data          # runs this with PYTHONPATH=vendor:<lab>
    PYTHONPATH=vendor uv run --project backend python scripts/gen_thresholds.py [--no-write]

Writes `backend/app/evidence/thresholds.json` (checked in; `app/evidence/plausibility/thresholds.py`
reads it at import): S2 train p0.1-p99.9, the no-spin carry fits (S5 / S11), the G4 / G5 body
lines, the G9 ego-carry percentile and the G14 reference-spec frequencies. Then it runs the app's
own rules (v1 + W2) and prints:

1. how many clean train shots S1-S3 reject (it should be none; S2 only ever confirms),
2. per-rule rates on clean train sessions, and how close `CARRY_FIT` is to the pack's `physics.fly`,
3. the validation figures on **dev**: clean reject / confirm shares, and the catch rate for
   injected errors (misreads, swapped columns, km/h, carry in metres, body-value unit mix-ups).

Offline only: this script may read train labels (and dev for validation); it never reads test.
All golfer data is simulated by the organiser pack.
"""

