# Empirical spec combinations for G14 plausibility checks
SPEC_COMBINATIONS: dict[str, int] = _RAW.get("spec_combinations", {})
SPEC_COMBINATIONS_TOTAL: int = int(_RAW.get("spec_combinations_total", 20000))


def spec_combination_frequency(
    head: str, flex: str, length_in: float, lie_deg: int | float, grip: str
) -> float:
    """Return the relative frequency of this spec combination in train reference specs."""
    if SPEC_COMBINATIONS_TOTAL <= 0:
        return 0.0
    key = f"{head}|{flex}|{float(length_in)}|{int(round(lie_deg))}|{grip}"
    return SPEC_COMBINATIONS.get(key, 0) / SPEC_COMBINATIONS_TOTAL


def is_rare_spec_combination(
    head: str,
    flex: str,
    length_in: float,
    lie_deg: int | float,
    grip: str,
    threshold: float = 0.001,
) -> bool:
    """Check if the combination occurs in < threshold (default 0.1% for G14)."""
    return spec_combination_frequency(head, flex, length_in, lie_deg, grip) < threshold


